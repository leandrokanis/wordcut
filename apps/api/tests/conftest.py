"""Fixtures of the API test suite: a fictitious Access team and tokens signed here.

Every key pair is generated by the test; no real token, key or e-mail is used (ADR-0017).
"""

from __future__ import annotations

import time
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

import jwt
import pytest
from cryptography.hazmat.primitives.asymmetric import rsa

# The .invalid top-level domain never resolves (RFC 2606).
TEAM_DOMAIN = "equipe.exemplo.invalid"
AUDIENCE = "aud-de-teste"
KEY_ID = "chave-1"
TOKEN_LIFETIME_SECONDS = 300

Sign = Callable[..., str]


@dataclass(frozen=True)
class AccessTeam:
    """The Access team the API is configured with in the tests."""

    domain: str = TEAM_DOMAIN
    audience: str = AUDIENCE


@dataclass
class StaticKeys:
    """A ``KeySource`` double: the public keys of the team, by ``kid``."""

    by_kid: dict[str, rsa.RSAPublicKey] = field(default_factory=dict)

    def public_key(self, kid: str) -> rsa.RSAPublicKey | None:
        return self.by_kid.get(kid)


@pytest.fixture(autouse=True)
def no_identity_from_the_shell(monkeypatch: pytest.MonkeyPatch) -> None:
    """``create_app()`` reads these variables; the shell running the tests must not set them."""
    for variable in ("WORDCUT_ACCESS_TEAM_DOMAIN", "WORDCUT_ACCESS_AUD", "WORDCUT_DEV_EMAIL"):
        monkeypatch.delenv(variable, raising=False)


@pytest.fixture
def team() -> AccessTeam:
    return AccessTeam()


@pytest.fixture(scope="session")
def team_key() -> rsa.RSAPrivateKey:
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


@pytest.fixture(scope="session")
def stranger_key() -> rsa.RSAPrivateKey:
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


@pytest.fixture
def team_keys(team_key: rsa.RSAPrivateKey) -> StaticKeys:
    return StaticKeys({KEY_ID: team_key.public_key()})


def access_claims(email: str | None) -> dict[str, Any]:
    """The claims of a valid Access token for ``email``, as Cloudflare signs them."""
    now = int(time.time())
    return {
        "aud": [AUDIENCE],
        "iss": f"https://{TEAM_DOMAIN}",
        "email": email,
        "iat": now,
        "exp": now + TOKEN_LIFETIME_SECONDS,
    }


@pytest.fixture
def sign(team_key: rsa.RSAPrivateKey) -> Sign:
    """Sign an Access token for ``email`` with the team key; keywords replace claims.

    ``key`` and ``kid`` replace the signing key and the key id of the header; a claim given
    as ``None`` is left out.
    """

    def signed(
        email: str | None = "assistente@exemplo.org",
        key: rsa.RSAPrivateKey | None = None,
        kid: str = KEY_ID,
        **claims: Any,
    ) -> str:
        payload = {**access_claims(email), **claims}
        payload = {name: value for name, value in payload.items() if value is not None}
        return jwt.encode(payload, key or team_key, algorithm="RS256", headers={"kid": kid})

    return signed
