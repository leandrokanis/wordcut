def access_claims(email: str | None) -> dict[str, Any]:
    """The claims of a valid Access token for ``email``, as Cloudflare signs them."""
    now = int(time.time())
    return {
        "aud": [AUDIENCE],
        "iss": f"https://{TEAM_DOMAIN}",
        "email": email,
        "iat": now,
        "exp": now + TOKEN_LIFETIME_SECONDS,
    }


@pytest.fixture
def sign(team_key: rsa.RSAPrivateKey) -> Sign:
    """Sign an Access token for ``email`` with the team key; keywords replace claims.

    ``key`` and ``kid`` replace the signing key and the key id of the header; a claim given
    as ``None`` is left out.
    """

    def signed(
        email: str | None = "assistente@exemplo.org",
        key: rsa.RSAPrivateKey | None = None,
        kid: str = KEY_ID,
        **claims: Any,
    ) -> str:
        payload = {**access_claims(email), **claims}
        payload = {name: value for name, value in payload.items() if value is not None}
        return jwt.encode(payload, key or team_key, algorithm="RS256", headers={"kid": kid})

    return signed


